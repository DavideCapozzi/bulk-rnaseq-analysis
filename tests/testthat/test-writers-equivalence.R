test_that("tables are snake_case, have a meta sidecar, and gzip output is deterministic", {
  d <- tempfile()
  x <- data.frame(feature_id = c("a", "b"), value = c(1.5, NA))
  p1 <- write_table(x, d, "t1", list(description = "x"), gzip = TRUE)
  md5a <- md5_file(p1)
  Sys.sleep(1.1)
  p2 <- write_table(x, d, "t1", list(description = "x"), gzip = TRUE)
  expect_equal(md5_file(p2), md5a)
  meta <- jsonlite::fromJSON(file.path(d, "t1.meta.json"))
  expect_equal(meta$columns, c("feature_id", "value"))
  expect_error(write_table(data.frame(BadName = 1), d, "t2"), "not in snake_case: BadName")
  expect_error(write_table(x, d, "Bad-Name"), "must be snake_case")
})

test_that("Excel exports are byte-identical across runs and carry the inference scope", {
  tabs <- list(res = data.frame(a = 1, inference_scope = "conditional_on_contrast"))
  f1 <- tempfile(fileext = ".xlsx")
  f2 <- tempfile(fileext = ".xlsx")
  write_module_outputs(list(tables = tabs, figures = list(), meta = list()), tempfile(), list(p = 1), xlsx_path = f1)
  Sys.sleep(1.1)
  write_module_outputs(list(tables = tabs, figures = list(), meta = list()), tempfile(), list(p = 1), xlsx_path = f2)
  expect_equal(md5_file(f1), md5_file(f2))
  info <- as.data.frame(readxl::read_excel(f1, sheet = "Info"))
  expect_equal(info$value[info$parameter == "inference_scope"], "conditional_on_contrast")
})

test_that("compare_tables distinguishes identical, tolerance, explained rounding and differences", {
  a <- data.frame(id = c("x", "y"), v = c(1.23456, 2), s = c("p", "q"))
  expect_equal(compare_tables(a, a, "id")$status, "identical")
  expect_equal(compare_tables(a, transform(a, v = v * (1 + 1e-10)), "id")$status, "equal_within_tolerance")
  expect_equal(compare_tables(a, transform(a, v = v * (1 + 1e-6)), "id")$status, "different")
  r <- transform(a, v = round(v, 2))
  out <- compare_tables(r, a, "id", round_ref = list(v = list(digits = 2)))
  expect_equal(out$status, "different_explained")
  expect_equal(compare_tables(a, transform(a, s = c("p", "z")), "id")$mismatched_columns, "s")
  expect_equal(compare_tables(a, a[1, ], "id")$status, "different")
})
