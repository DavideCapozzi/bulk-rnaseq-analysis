#' Write a methods text for the run
#'
#' Builds `report/methods.md` from the resolved config and the module statuses: a paragraph on the inputs, one
#' paragraph per module that ran (templates in `inst/templates/methods/<module>.md`), the software versions and the
#' references the paragraphs cite. A template is Markdown with two constructs: `{{path}}` is replaced by a value
#' (a dotted path into the resolved config, `pkg.<package>` for a package version, or `x.<name>` for a phrase
#' built by [methods_phrases()]); `{{#path}}...{{/path}}` keeps its content only when the value is set (not
#' `NULL`, `FALSE`, empty or `NA`). The first line of a template may list citation keys of
#' `inst/templates/methods/references.yaml` as `<!-- refs: key1, key2 -->`.
#'
#' @param cfg Config from [read_config()] (defaults filled).
#' @param out `character(1)`. Project output folder (reads `00_provenance/capabilities.json`).
#' @return Path of `report/methods.md`, invisibly.
#' @examples
#' \donttest{
#' # called by the report step when export.methods is true
#' }
#' @export
write_methods <- function(cfg, out) {
  caps <- read_capabilities(out)
  ran <- caps$module[caps$status == "run"]
  lines <- c(
    paste0("# Methods: ", cfg$project$name), "",
    paste0(
      "Generated by bulkrnaseq ", utils::packageVersion("bulkrnaseq"), " from the resolved configuration of the ",
      "run (00_provenance/config_resolved.yaml). Check it against the analysis actually reported before use."
    ), ""
  )
  body <- methods_paragraphs(cfg, ran)
  lines <- c(lines, body$text)
  notes <- cfg$export$methods_notes
  if (!is.null(notes) && nzchar(notes)) lines <- c(lines, "## Notes", "", notes, "")
  lines <- c(lines, "## Software", "", methods_software(body$packages), "")
  refs <- methods_references(body$refs)
  if (length(refs) > 0) lines <- c(lines, "## References", "", paste0(seq_along(refs), ". ", refs), "")
  dir.create(file.path(out, "report"), showWarnings = FALSE, recursive = TRUE)
  path <- file.path(out, "report", "methods.md")
  writeLines(lines, path)
  invisible(path)
}

# Paragraphs of the inputs and of the modules that ran, with the citation keys and packages they use.
methods_paragraphs <- function(cfg, ran) {
  registry <- read_registry()
  phrases <- methods_phrases(cfg)
  text <- character()
  refs <- character()
  packages <- character()
  for (name in c("inputs", intersect(names(registry), ran))) {
    tpl <- methods_template(name)
    if (is.null(tpl)) abort("methods: no template for module '", name, "' (inst/templates/methods/", name, ".md)")
    title <- if (name == "inputs") "Inputs and gene annotation" else module_dir_name(name, registry)
    params <- if (name == "inputs") list() else module_params(cfg, name)
    para <- render_methods_template(tpl$body, cfg, params, phrases)
    text <- c(text, paste0("## ", title), "", para, "")
    refs <- c(refs, tpl$refs)
    packages <- c(packages, tpl$packages)
  }
  list(text = text, refs = unique(refs), packages = unique(packages))
}

methods_template <- function(name) {
  path <- system.file("templates", "methods", paste0(name, ".md"), package = "bulkrnaseq")
  if (!nzchar(path)) {
    return(NULL)
  }
  txt <- readLines(path, warn = FALSE, encoding = "UTF-8")
  header <- function(tag) {
    h <- grep(paste0("^<!-- ", tag, ":"), txt, value = TRUE)
    if (length(h) == 0) {
      return(character())
    }
    v <- trimws(strsplit(sub(paste0("^<!-- ", tag, ":(.*)-->\\s*$"), "\\1", h[[1]]), ",")[[1]])
    v[nzchar(v)]
  }
  body <- txt[!grepl("^<!-- (refs|packages):", txt)]
  list(body = paste(body, collapse = "\n"), refs = header("refs"), packages = header("packages"))
}

#' Render a methods template
#'
#' @param template `character(1)`. Template text.
#' @param cfg Resolved config.
#' @param params `list`. Parameters of the module (defaults filled), addressable as `p.<path>`.
#' @param phrases Named `list` of phrases, addressable as `x.<name>`.
#' @return `character(1)`. Rendered text, with consecutive blank lines collapsed.
#' @examples
#' render_methods_template("min {{p.n}}{{#p.flag}}, flagged{{/p.flag}}", list(), list(n = 3, flag = FALSE), list())
#' @export
render_methods_template <- function(template, cfg, params, phrases) {
  lookup <- function(path) {
    parts <- strsplit(path, ".", fixed = TRUE)[[1]]
    if (parts[[1]] == "pkg") {
      return(methods_package_version(parts[[2]]))
    }
    root <- switch(parts[[1]],
      p = params,
      x = phrases,
      cfg
    )
    keys <- if (parts[[1]] %in% c("p", "x")) parts[-1] else parts
    for (k in keys) {
      if (!is.list(root)) {
        return(NULL)
      }
      root <- root[[k]]
    }
    root
  }
  is_set <- function(v) !(is.null(v) || isFALSE(v) || length(v) == 0 || all(is.na(v)) || identical(v, ""))
  out <- template
  repeat {
    m <- regmatches(out, regexec("\\{\\{#([^}]+)\\}\\}", out))[[1]]
    if (length(m) == 0) break
    key <- m[[2]]
    open <- paste0("{{#", key, "}}")
    close <- paste0("{{/", key, "}}")
    start <- regexpr(open, out, fixed = TRUE)
    end <- regexpr(close, substring(out, start), fixed = TRUE)
    if (end < 0) abort("methods template: '", open, "' is not closed")
    inner <- substring(out, start + nchar(open), start + end - 2)
    keep <- if (is_set(lookup(key))) inner else ""
    out <- paste0(substring(out, 1, start - 1), keep, substring(out, start + end - 1 + nchar(close)))
  }
  repeat {
    m <- regmatches(out, regexec("\\{\\{([^}#/]+)\\}\\}", out))[[1]]
    if (length(m) == 0) break
    v <- lookup(m[[2]])
    if (length(v) == 0) abort("methods template: no value for '", m[[2]], "'")
    val <- if (is.list(v)) paste(unlist(v), collapse = ", ") else paste(format_methods_value(v), collapse = ", ")
    out <- sub(m[[1]], val, out, fixed = TRUE)
  }
  out <- gsub("[ \t]+\n", "\n", out)
  gsub("\n{3,}", "\n\n", trimws(out))
}

format_methods_value <- function(v) {
  if (is.numeric(v)) format(v, trim = TRUE, scientific = FALSE, drop0trailing = TRUE) else as.character(v)
}

methods_package_version <- function(p) {
  tryCatch(as.character(utils::packageVersion(p)), error = function(e) "not installed")
}

methods_software <- function(packages) {
  pk <- sort(unique(c("bulkrnaseq", packages)))
  v <- vapply(pk, methods_package_version, "")
  paste0(
    R.version.string, ". Packages: ", paste0(pk, " ", v, collapse = ", "),
    ". The workflow runs with Snakemake; exact versions of every package are in 00_provenance/run_manifest.json."
  )
}

methods_references <- function(keys) {
  if (length(keys) == 0) {
    return(character())
  }
  refs <- yaml::read_yaml(package_file("templates", "methods", "references.yaml"))
  missing <- setdiff(keys, names(refs))
  if (length(missing) > 0) abort("methods: unknown reference key(s): ", toString(missing))
  unlist(refs[keys], use.names = FALSE)
}

#' Phrases of the methods text
#'
#' Pieces of text that depend on several config fields (inputs, designs, gene filter, collections, ...), used by
#' the methods templates as `{{x.<name>}}`.
#'
#' @param cfg Resolved config.
#' @return Named `list` of `character(1)` (absent when not applicable).
#' @examples
#' methods_phrases(list(thresholds = list(padj = 0.05, abs_fold_change = 1.5)))$de_thresholds
#' @export
methods_phrases <- function(cfg) {
  x <- list()
  inp <- cfg$inputs %||% list()
  items <- cfg$resources$items %||% list()
  version_of <- function(key) items[[key]]$version %||% basename(items[[key]]$source %||% key)
  if (!is.null(inp$counts)) {
    x$counts <- paste0("gene-level read counts (", methods_adapter_label(inp$counts$adapter), ")")
  }
  if (!is.null(inp$abundance)) x$abundance <- paste0("abundances (", methods_adapter_label(inp$abundance$adapter), ")")
  if (!is.null(inp$normalized)) {
    x$normalized <- paste0("normalised counts", if (!is.null(inp$normalized$description)) {
      paste0(" (", inp$normalized$description, ")")
    })
  }
  tabs <- inp$contrast_tables %||% list()
  if (length(tabs) > 0) {
    x$contrast_tables <- paste(vapply(tabs, function(t) {
      paste0(
        t$id, " (", t$adapter, " table", if (!is.null(t$df_residual)) paste0(", ", t$df_residual, " residual df"), ")"
      )
    }, ""), collapse = "; ")
  }
  if (!is.null(cfg$samples$factors)) {
    x$factors <- paste(vapply(names(cfg$samples$factors), function(f) {
      paste0(f, " (", paste(unlist(cfg$samples$factors[[f]]), collapse = ", "), ")")
    }, ""), collapse = "; ")
  }
  x$id_type <- c(
    ensembl_gene_id = "Ensembl gene IDs", gene_symbol = "gene symbols", entrez_id = "Entrez gene IDs"
  )[[cfg$annotation$id_type %||% "ensembl_gene_id"]]
  gtf <- cfg$annotation$gtf %||% "gtf"
  if (!is.null(items[[gtf]])) x$annotation <- version_of(gtf)
  gf <- cfg$gene_filter %||% list()
  if (length(gf) > 0) {
    x$gene_filter <- paste0(
      if (!is.null(gf$biotypes)) paste0("biotypes ", paste(unlist(gf$biotypes), collapse = " and "), "; "),
      if (isTRUE(gf$exclude_mitochondrial)) "mitochondrial genes removed; ",
      "at least ", gf$min_cpm, " counts per million in at least ", gf$min_samples, " samples",
      switch(gf$sex_genes %||% "keep",
        drop_xist_y = "; chromosome Y genes and XIST removed",
        drop_xy = "; chromosome X and Y genes removed",
        ""
      )
    )
  }
  designs <- cfg$designs %||% list()
  if (length(designs) > 0) {
    x$designs <- paste(vapply(designs, function(d) {
      paste0(
        d$id, " (", d$formula,
        if (!is.null(d$contrast)) paste0("; ", d$contrast[[1]], " ", d$contrast[[2]], " vs ", d$contrast[[3]]), ")"
      )
    }, ""), collapse = "; ")
  }
  cons <- cfg$contrasts %||% list()
  if (length(cons) > 0) {
    x$contrasts <- paste(vapply(cons, function(cn) {
      num <- paste(unlist(cn$numerator), collapse = "+")
      den <- paste(unlist(cn$denominator), collapse = "+")
      paste0(cn$id, " (", num, " vs ", den, ")")
    }, ""), collapse = "; ")
  }
  pairs <- cfg$contrast_pairs %||% list()
  if (length(pairs) > 0) {
    x$contrast_pairs <- paste(vapply(pairs, function(p) paste0(p$id, " (", p$first, ", ", p$second, ")"), ""),
      collapse = "; "
    )
  }
  th <- cfg$thresholds %||% list()
  if (!is.null(th$abs_fold_change)) {
    x$de_thresholds <- paste0(
      "adjusted p-value <= ", th$padj %||% 0.05, " (or posterior probability >= ", th$posterior_prob %||% 0.8,
      " for NOISeq-type tables) and |fold change| >= ", th$abs_fold_change, " (|log2 fold change| >= ",
      format(round(log2(th$abs_fold_change), 3), nsmall = 0), ")"
    )
  }
  gt <- cfg$modules$geneset_test
  if (!is.null(gt)) {
    x$geneset_collections <- paste(vapply(gt$collections %||% list(), function(cl) {
      paste0(
        cl$collection, if (!is.null(cl$subcollection)) paste0(" ", cl$subcollection),
        if (!is.null(cl$set_pattern)) paste0(" (sets matching ", cl$set_pattern, ")")
      )
    }, ""), collapse = ", ")
    if (!is.null(gt$resource) && !is.null(items[[gt$resource]])) x$geneset_resource <- version_of(gt$resource)
    x$geneset_universes <- methods_universes(gt$universes)
    gm <- unlist(gt$methods)
    x$geneset_methods <- paste(c(
      if ("camera_pr" %in% gm) {
        paste0(
          "limma cameraPR (inter-gene correlation ", paste(unlist(gt$inter_gene_cor), collapse = " and "),
          if (isTRUE(any(unlist(gt$use_ranks)))) "; also on ranks", ")"
        )
      },
      if ("fgsea" %in% gm) "pre-ranked fgsea (multilevel, seeded)"
    ), collapse = " and ")
    x$geneset_ranking <- if (identical(gt$ranking_statistic, "stat")) {
      "the test statistic (DESeq2 Wald statistic)"
    } else {
      "the log2 fold change"
    }
  }
  sg <- cfg$modules$signatures
  if (!is.null(sg)) {
    n_msig <- length(unlist(sg$msigdb_sets))
    n_custom <- length(sg$custom_sets %||% list())
    res_version <- if (!is.null(sg$resource) && !is.null(items[[sg$resource]])) version_of(sg$resource)
    x$signature_sets <- paste0(
      n_msig, " MSigDB set(s)", if (n_msig > 0) {
        paste0(
          " (", if (!is.null(res_version)) paste0(res_version, ": "), paste(unlist(sg$msigdb_sets), collapse = ", "),
          ")"
        )
      },
      if (n_custom > 0) paste0(" and ", n_custom, " custom set(s)"),
      if (length(sg$composites %||% list()) > 0) {
        paste0(
          "; composites ",
          paste(vapply(sg$composites, function(cp) paste0(cp$id, " = ", cp$up, " vs ", cp$down), ""), collapse = ", ")
        )
      }
    )
    x$signature_universes <- methods_universes(sg$universes)
  }
  mk <- cfg$modules$markers
  if (!is.null(mk) && length(mk$panels %||% list()) > 0) {
    x$marker_panels <- paste(vapply(mk$panels, function(p) p$label %||% p$id, ""), collapse = ", ")
  }
  x
}

methods_universes <- function(universes) {
  paste(vapply(universes %||% list(), function(u) {
    if (identical(u$subset, "all")) paste0(u$id, " (all genes)") else paste0(u$id, " (", u$subset, ")")
  }, ""), collapse = ", ")
}

methods_adapter_label <- function(adapter) {
  labels <- c(
    matrix = "a table delivered by the provider", star_reads_per_gene = "STAR ReadsPerGene files",
    stringtie_gene_abundance = "StringTie gene abundance files"
  )
  if (adapter %in% names(labels)) labels[[adapter]] else paste0(adapter, " files")
}
